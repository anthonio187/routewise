export const dictionaries: Record<string, Record<TranslationKey, string>> = {
  en,
  fr,
  es,
  pt,
};

export const supportedLanguages = [
  { code: 'en', label: 'English' },
  { code: 'fr', label: 'Français' },
  { code: 'es', label: 'Español' },
  { code: 'pt', label: 'Português' },
] as const;

export function detectLanguage(): string {
  const explicit = settingsStore.get().language;
  if (explicit && dictionaries[explicit]) return explicit;
  try {
    const lang = (navigator.languages?.[0] ?? navigator.language ?? 'en').slice(0, 2).toLowerCase();
    return dictionaries[lang] ? lang : 'en';
  } catch {
    return 'en';
  }
}

interface I18nContextValue {
  locale: string;
  setLocale: (locale: string) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<string>(() => detectLanguage());

  const setLocale = useCallback((next: string) => {
    if (!dictionaries[next]) return;
    settingsStore.set({ language: next });
    setLocaleState(next);
  }, []);

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      const dict = dictionaries[locale] ?? en;
      let text = dict[key] ?? en[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{\\{${name}\\}\\}`, 'g'), String(value));
        }
      }
      return text;
    },
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

/** Map server notice codes to localised messages (unknown codes fall back to the API text). */
export function noticeText(
  code: string,
  serverMessage: string,
  t: I18nContextValue['t'],
): string {
  const map: Record<string, TranslationKey> = {
    no_transit_itineraries: 'notice.noTransit',
    no_database: 'notice.noDatabase',
    fares_unavailable: 'notice.fares',
    currency_unknown: 'notice.currency',
    step_free_unverified: 'notice.stepFree',
    transit_provider_error: 'notice.provider',
    local_gtfs_without_database: 'notice.provider',
  };
  const key = map[code];
  return key ? t(key) : serverMessage;
}
